#!/usr/bin/env python3
"""Validate generated Codex/agentskills.io skill layout and portable metadata."""
import importlib.util
import yaml
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROUTER = ROOT / "bin" / "skill-router.py"
SPEC = importlib.util.spec_from_file_location("skill_router", ROUTER)
router = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(router)

errors = []
generated = []
for path in sorted((ROOT / ".agents" / "skills").glob("*/SKILL.md")):
    text = path.read_text()
    if "GENERATED by bin/gen-codex-skills.mjs" not in text:
        continue
    generated.append(path)
    try:
        fm, _ = router.parse_frontmatter(text)
    except ValueError as exc:
        errors.append(f"{path.relative_to(ROOT)}: {exc}")
        continue
    allowed = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
    unknown = sorted(set(fm) - allowed)
    if unknown:
        errors.append(f"{path.relative_to(ROOT)}: unknown portable fields {unknown}")
    if not isinstance(fm.get("name"), str) or fm["name"] != path.parent.name:
        errors.append(f"{path.relative_to(ROOT)}: name must equal directory name")
    if not isinstance(fm.get("description"), str) or not fm["description"].strip():
        errors.append(f"{path.relative_to(ROOT)}: description must be a non-empty string")
    if "compatibility" in fm and not isinstance(fm["compatibility"], str):
        errors.append(f"{path.relative_to(ROOT)}: compatibility must be a string")
    ui_path = path.parent / "agents" / "openai.yaml"
    if not ui_path.is_file():
        errors.append(f"{path.relative_to(ROOT)}: missing agents/openai.yaml")
    else:
        try:
            ui = yaml.safe_load(ui_path.read_text())
            interface = ui.get("interface", {}) if isinstance(ui, dict) else {}
            for field in ("display_name", "short_description", "default_prompt"):
                if not isinstance(interface.get(field), str) or not interface[field].strip():
                    errors.append(f"{ui_path.relative_to(ROOT)}: missing string interface.{field}")
        except yaml.YAMLError as exc:
            errors.append(f"{ui_path.relative_to(ROOT)}: invalid YAML: {exc}")

if len(generated) != 24:
    errors.append(f"expected 24 generated portable skills, found {len(generated)}")
if errors:
    print("Portable skill validation failed:", file=sys.stderr)
    for error in errors:
        print(f"- {error}", file=sys.stderr)
    sys.exit(1)
print(f"Portable skill validation passed ({len(generated)} skills).")
