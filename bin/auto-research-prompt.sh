#!/usr/bin/env bash
#
# auto-research-prompt.sh — emit the per-project `Auto Research Prompt.md` audit (directive §12)
# from the research-orchestrator ledger. Full research transparency: the exact original request, the
# real per-provider research responses (opencode/DeepSeek · codex · claude), the comparison, the
# original-vs-expanded requirements, the SYNTHESIZED implementation prompt (before execution), the
# execution results, and the final synopsis. Honest by construction: fields with no captured data are
# marked "(not captured this run)" — never fabricated. The file is git-EXCLUDED by default (local
# `.git/info/exclude`, NOT team `.gitignore`).
#
# Ledger schema (written by research-orchestrator.sh, secret-free NDJSON):
#   session line: {"k","n","provider","role","question","launched","out","used","why","at"}
#   verdict line: {"verdict":true,"k","provider","used","why","at"}
# The reader folds the latest verdict per (k,provider) into its session for the Comparison.
#
# Usage:
#   auto-research-prompt.sh [--research-dir DIR] [--input FILE|STR] [--synthesized FILE|STR] \
#                           [--project NAME] [--out FILE] [--no-exclude]
# Reads: $RESEARCH_DIR/sessions.ndjson (+ each session's `.out` file). Writes: ./Auto Research Prompt.md.
#
# Exit: 0 ok (file written even with an empty/absent ledger — honest placeholders) · 2 usage.

set -uo pipefail

# ---------------------------------------------------------------------------- styling + env
# shellcheck disable=SC1091
if [ -f "${HOME}/.claude/hooks/style.sh" ]; then source "${HOME}/.claude/hooks/style.sh"; fi
# Minimal fallbacks if style.sh is absent (keeps the script CI-safe standalone).
if ! command -v emdash_success >/dev/null 2>&1; then
  emdash_header() { printf '\n== %s ==\n' "$*" >&2; }
  emdash_log() { printf '  %s\n' "$1" >&2; }
  emdash_success() { printf '  [ok] %s\n' "$*" >&2; }
  emdash_warn() { printf '  [warn] %s\n' "$*" >&2; }
  emdash_info() { printf '  [i] %s\n' "$*" >&2; }
  emdash_error() { printf '  [err] %s\n' "$*" >&2; }
fi

HAS_JQ=0
command -v jq >/dev/null 2>&1 && HAS_JQ=1

# ---------------------------------------------------------------------------- arg parse
val() { # val <--name> <args...> — echo the value after --name (empty if absent)
  local want="$1"
  shift
  while [ "$#" -gt 0 ]; do
    [ "$1" = "$want" ] && {
      printf '%s' "${2:-}"
      return
    }
    shift
  done
}
has() { # has <--flag> <args...> — 0 if present
  local w="$1"
  shift
  for a in "$@"; do [ "$a" = "$w" ] && return 0; done
  return 1
}

RDIR="$(val --research-dir "$@")"
RDIR="${RDIR:-${RESEARCH_DIR:-${PWD}/.research}}"
LEDGER="${RDIR}/sessions.ndjson"
INPUT="$(val --input "$@")"
SYNTH="$(val --synthesized "$@")"
PROJECT="$(val --project "$@")"
PROJECT="${PROJECT:-$(basename "${PWD}")}"
OUT="$(val --out "$@")"
OUT="${OUT:-${PWD}/Auto Research Prompt.md}"
NOW="$(date '+%Y-%m-%d %H:%M:%S %Z' 2>/dev/null || date -u +%Y-%m-%dT%H:%M:%SZ)"
ISO="$(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || printf 'unknown')"

# A string that may be a readable file path OR a literal value → emit its content either way.
read_maybe_file() { if [ -f "$1" ]; then cat -- "$1"; else printf '%s' "$1"; fi; }
section_or_placeholder() {
  if [ -n "$1" ]; then read_maybe_file "$1"; else printf '_(not captured this run)_'; fi
}
# Human label for a provider key.
provider_label() {
  case "$1" in
    opencode) printf 'OpenCode / DeepSeek' ;;
    codex) printf 'Codex' ;;
    claude) printf 'Claude' ;;
    *) printf '%s' "$1" ;;
  esac
}

LEDGER_OK=0
if [ "$HAS_JQ" = "1" ] && [ -s "$LEDGER" ]; then
  # Guard against a malformed ledger: require at least one valid JSON line.
  if jq -e . "$LEDGER" >/dev/null 2>&1; then LEDGER_OK=1; else emdash_warn "ledger at ${LEDGER} is not valid NDJSON — emitting placeholders"; fi
fi

# ============================================================================ document
{
  printf '# Auto Research Prompt\n\n'
  printf '> Latest top-level prompt-expansion run for **%s**. Full research transparency (directive §12).\n' "$PROJECT"
  printf '> Regenerated by `auto-research-prompt.sh` from `%s`. Git-excluded — do not commit.\n\n' "$LEDGER"

  # ---- §12 · Input (the exact original request) --------------------------------------
  printf '## Input\n\nThe exact original request that triggered this prompt-expansion run.\n\n```\n%s\n```\n\n' "$(section_or_placeholder "$INPUT")"

  # ---- §12 · Research Started ---------------------------------------------------------
  printf '## Output\n\n### Research Started\n\n'
  printf -- '- Timestamp: %s (`%s`)\n' "$NOW" "$ISO"
  printf -- '- Project: %s\n' "$PROJECT"
  printf -- '- Ledger: `%s`\n' "$LEDGER"
  if [ "$LEDGER_OK" = "1" ]; then
    provs="$(jq -rs '[.[]|select(.verdict!=true)|.provider]|unique|join(", ")' "$LEDGER" 2>/dev/null)"
    n="$(jq -rs '[.[]|select(.verdict!=true)]|length' "$LEDGER" 2>/dev/null)"
    ran="$(jq -rs '[.[]|select(.verdict!=true and .launched==true)]|length' "$LEDGER" 2>/dev/null)"
    printf -- '- Models/providers: %s\n' "${provs:-none}"
    printf -- '- Sessions: %s (ran %s)\n\n' "${n:-0}" "${ran:-0}"
  else
    printf -- '- Models/providers: _(no ledger — run `research-orchestrator.sh` first)_\n\n'
  fi

  # ---- §12 · Per-provider Full Response (OpenCode/DeepSeek · Codex · Claude) -----------
  # One section per provider, in breadth→depth order, each session's SUBMITTED prompt + RETURNED
  # content rendered verbatim (char-capped). Fields are @base64-encoded by jq and decoded in bash so
  # questions/paths with spaces or newlines survive intact (the prior space-split reader corrupted them).
  if [ "$LEDGER_OK" = "1" ]; then
    for prov in opencode codex claude; do
      title="$(provider_label "$prov")"
      count="$(jq -rs --arg p "$prov" '[.[]|select(.verdict!=true and .provider==$p)]|length' "$LEDGER" 2>/dev/null)"
      printf '### %s Research — Full Response\n\n' "$title"
      if [ "${count:-0}" -eq 0 ]; then
        printf '_(no %s session this run)_\n\n' "$prov"
        continue
      fi
      # Per-field base64 joined by ':' (base64 emits only [A-Za-z0-9+/=] — ':' is a safe, non-collapsing
      # separator that PRESERVES empty fields; a single tab/space would coalesce an empty `out`). One
      # record per line → each field decoded independently, so questions/paths with spaces, quotes, or
      # newlines survive verbatim (the prior space-split reader corrupted them).
      while IFS=: read -r k64 role64 launched out64 q64; do
        [ -n "$k64" ] || continue
        k="$(printf '%s' "$k64" | base64 --decode 2>/dev/null)"
        role="$(printf '%s' "$role64" | base64 --decode 2>/dev/null)"
        out="$(printf '%s' "$out64" | base64 --decode 2>/dev/null)"
        question="$(printf '%s' "$q64" | base64 --decode 2>/dev/null)"
        printf '#### session %s · %s\n\n' "${k:-?}" "${role:--}"
        printf -- '- Submitted prompt: `%s`\n' "${question:--}"
        printf -- '- Launched: %s\n\n' "${launched:-false}"
        if [ -n "$out" ] && [ -f "$out" ]; then
          printf 'Returned research content (verbatim, capped):\n\n```\n'
          head -c 6000 -- "$out"
          printf '\n```\n\n'
        elif [ "${launched:-false}" = "true" ]; then
          printf '_(launched, but no output file at `%s`)_\n\n' "${out:-?}"
        else
          printf '_(not run this session — see Research Comparison for why)_\n\n'
        fi
      done < <(jq -rs --arg p "$prov" '
        def flat: gsub("[\t\n]"; " ");
        .[] | select(.verdict!=true and .provider==$p)
        | ((.k//"?")|@base64) + ":" + ((.role//"-"|flat)|@base64) + ":"
          + (if .launched then "true" else "false" end) + ":"
          + ((.out//"")|@base64) + ":" + ((.question//"-"|flat)|@base64)
      ' "$LEDGER" 2>/dev/null)
    done
  else
    printf '### Research — Full Response\n\n_(no ledger — nothing to render)_\n\n'
  fi

  # ---- §12 · Research Comparison (honesty gate: used / not-used per session) -----------
  printf '### Research Comparison\n\nEvery session, and whether its result was USED in the final plan (+why).\n\n'
  if [ "$LEDGER_OK" = "1" ]; then
    printf '| session | provider | ran | used | why |\n|---|---|---|---|---|\n'
    jq -rs '
      (map(select(.verdict==true)) | map({key:(.k+"|"+.provider), value:.}) | from_entries) as $v
      | map(select(.verdict!=true))
      | .[]
      | . as $s
      | ($v[($s.k+"|"+$s.provider)] // {}) as $m
      | "| \($s.k) | \($s.provider) | \(if $s.launched then "yes" else "no" end) | "
        + "\(if $m.used==true then "USED" elif ($m.used==false or $s.used==false) then "not used" else "pending" end) | "
        + "\((($m.why // $s.why // "-") | gsub("[|\n]";" "))[0:160]) |"
    ' "$LEDGER" 2>/dev/null
    printf '\n'
  else
    printf '_(no ledger)_\n\n'
  fi

  # ---- §12 · Original vs Expanded ----------------------------------------------------
  printf '### Original vs Expanded\n\n'
  printf -- '- **Original:** the Input above — the literal request as received.\n'
  printf -- '- **Expanded:** the full arc the research surfaced (states · pages · gorgeous · AI-native · prod gates) — captured in the Synthesized Implementation Prompt below.\n\n'

  # ---- §12 · Synthesized Implementation Prompt (the plan, BEFORE execution) ----------
  printf '### Synthesized Implementation Prompt\n\nClaude-synthesized plan (a synthesis of all sessions, not a concat) — the prompt the build actually executes.\n\n%s\n\n' "$(section_or_placeholder "$SYNTH")"

  # ---- §12 · Execution Results + Final Synopsis (post-implementation) -----------------
  printf '### Execution Results\n\n_(populated post-implementation — not captured this run)_\n\n'
  printf '### Final Synopsis\n\n_(populated post-implementation — not captured this run)_\n'
} >"$OUT"

emdash_success "wrote ${OUT}"

# ---------------------------------------------------------------------------- git-exclude
# Local .git/info/exclude ONLY — never touches the team-tracked .gitignore.
if ! has --no-exclude "$@"; then
  GITDIR="$(git rev-parse --git-dir 2>/dev/null || true)"
  if [ -n "$GITDIR" ]; then
    EXC="${GITDIR}/info/exclude"
    mkdir -p "${GITDIR}/info"
    if ! grep -qxF 'Auto Research Prompt.md' "$EXC" 2>/dev/null; then
      printf 'Auto Research Prompt.md\n' >>"$EXC"
      emdash_info "git-excluded 'Auto Research Prompt.md' via ${EXC}"
    else
      emdash_info "already git-excluded"
    fi
  else
    emdash_info "not a git repo — skipped .git/info/exclude"
  fi
fi
