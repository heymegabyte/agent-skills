#!/usr/bin/env node
/**
 * gen-codex-skills.mjs — regenerate the `.agents/skills/` directory-format
 * mirror (OpenAI Codex / agentskills.io consumers) from the CURRENT numbered
 * category dirs. The mirror was a hand-cut Sep-2026 snapshot that drifted:
 * it still shipped retired categories (03, 17-20) and leaked Claude-adapter
 * paths (`~/.claude/**`, one machine-absolute `/Users/...`) into a non-Claude
 * surface (found by the fire-6 leak matrix; policy: rules/agent-neutrality.md).
 *
 * Behavior:
 *   - one discoverable skill directory per canonical category, plus the
 *     existing flat mirrors for consumers that read them by filename
 *   - adapter-path mapping: `~/.claude/CLAUDE.md` → `AGENTSKILLS.md`,
 *     `~/.claude/` → `<agent-home>/` (legend in the banner), absolute
 *     `/Users/<name>/.claude/` collapsed the same way
 *   - stale outputs for retired categories are deleted
 *   - hard assertion: no `~/.claude` / `/Users/` survives in any output
 *
 * Usage:
 *   node bin/gen-codex-skills.mjs           # regenerate + report
 *   node bin/gen-codex-skills.mjs --check   # exit 1 if mirror drifted (CI)
 */
import { readdirSync, statSync, readFileSync, writeFileSync, unlinkSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, '.agents', 'skills');
const CHECK = process.argv.includes('--check');

const BANNER = `<!-- GENERATED by bin/gen-codex-skills.mjs from the category's SKILL.md — do not hand-edit.
     Path legend: \`<agent-home>\` = your AI tool's config directory
     (Claude Code: ~/.claude · Codex: ~/.codex · others: see your tool's docs). -->`;

function transform(body, rootPrefix) {
  return body
    .replace(/\]\(\.\.\//g, `](${rootPrefix}`)
    .replace(/\/Users\/[A-Za-z0-9_-]+\/\.claude\//g, '<agent-home>/')
    .replace(/\/Users\/[A-Za-z0-9_-]+\/\.local\/bin\//g, '')
    .replace(/~\/\.claude\/CLAUDE\.md/g, 'AGENTSKILLS.md')
    .replace(/~\/\.claude\.json/g, '<agent-home>.json')
    .replace(/~\/\.claude\//g, '<agent-home>/')
    .replace(/~\/\.claude\b/g, '<agent-home>');
}

// Codex/agentskills.io consumers read name + description; the Claude-router
// keys (priority/pack/stage/triggers/paths, claude-code compat, model/effort
// metadata) are host-specific noise in this surface. Emit the open-standard
// minimum and keep the body untouched.
function slimFrontmatter(raw, dir) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return raw;
  const fm = m[1];
  const grab = (key) => {
    const r = fm.match(new RegExp(`^${key}: ?"?([^"\n]*)"?$`, 'm'));
    return r ? r[1].trim() : null;
  };
  const name = grab('name')?.replace(/^'([^']+)'$/, '$1') || dir;
  const desc = grab('description') || '';
  const license = grab('license');
  const slim = [
    '---',
    `name: "${name}"`,
    `description: "${desc}"`,
    ...(license ? [`license: "${license}"`] : []),
    'compatibility:',
    '  agentskills: ">=1.0.0"',
    `source: "${dir}/SKILL.md (heymegabyte/agent-skills)"`,
    '---',
    '',
  ].join('\n');
  return slim + raw.slice(m[0].length);
}

const dirs = readdirSync(ROOT)
  .filter((n) => /^\d\d-/.test(n) && statSync(join(ROOT, n)).isDirectory())
  .sort();
if (existsSync(join(ROOT, 'openclaw-integration', 'SKILL.md'))) dirs.push('openclaw-integration');

const expected = new Map();
for (const dir of dirs) {
  const src = join(ROOT, dir, 'SKILL.md');
  if (!existsSync(src)) continue;
  const raw = readFileSync(src, 'utf8');
  const frontmatter = slimFrontmatter(raw, dir);
  const body = transform(frontmatter, '../../');
  // Assert BEFORE the banner goes in — the banner's legend legitimately names ~/.claude.
  if (/~\/\.claude|\/Users\//.test(body)) {
    console.error(`✗ ${dir}: adapter-path leak survived transform — fix the mapping`);
    process.exit(1);
  }
  // Insert the banner right after the closing frontmatter fence.
  const out = body.replace(/^(---\n[\s\S]*?\n---\n)/, `$1\n${BANNER}\n`);
  expected.set(`${dir}.md`, out);
  const name = frontmatter.match(/^name: "([a-z0-9-]+)"$/m)?.[1];
  if (!name || expected.has(`${name}/SKILL.md`)) {
    throw new Error(`Invalid or duplicate Codex skill name in ${dir}/SKILL.md`);
  }
  expected.set(`${name}/SKILL.md`, transform(frontmatter, '../../../')
    .replace(/^(---\n[\s\S]*?\n---\n)/, `$1\n${BANNER}\n`));
}

const existing = existsSync(OUT_DIR) ? readdirSync(OUT_DIR, { withFileTypes: true }).flatMap((entry) => {
  if (entry.isFile() && entry.name.endsWith('.md')) return [entry.name];
  const skill = `${entry.name}/SKILL.md`;
  if (entry.isDirectory() && existsSync(join(OUT_DIR, skill))
    && readFileSync(join(OUT_DIR, skill), 'utf8').includes(BANNER)) return [skill];
  return [];
}) : [];
const stale = existing.filter((n) => !expected.has(n));
let drifted = [...stale.map((n) => `${n} (stale)`)];
for (const [name, content] of expected) {
  const p = join(OUT_DIR, name);
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (name.endsWith('/SKILL.md') && cur !== null && !cur.includes(BANNER)) {
    throw new Error(`Refusing to overwrite a manually maintained skill at .agents/skills/${name}`);
  }
  if (cur !== content) drifted.push(name);
}

if (CHECK) {
  // Also fail when mirror files are neither tracked nor visible as unignored
  // additions. CI still fails if a generated addition was not committed because
  // it is absent from the fresh checkout; local validation does not require staging.
  const { execSync } = await import('node:child_process');
  const visibleFiles = new Set(execSync("git ls-files --cached --others --exclude-standard -- .agents/skills", { cwd: ROOT })
    .toString().trim().split('\n'));
  const visible = [...expected.keys()].filter((file) => visibleFiles.has(`.agents/skills/${file}`)).length;
  if (visible !== expected.size) {
    console.error(`✗ gen-codex-skills: ${expected.size} mirror files on disk but only ${visible} are repository-visible — check .gitignore anchoring`);
    process.exit(1);
  }
  if (drifted.length) {
    console.error(`✗ gen-codex-skills: ${drifted.length} mirror file(s) drifted — run \`node bin/gen-codex-skills.mjs\`:`);
    for (const d of drifted) console.error(`  · ${d}`);
    process.exit(1);
  }
  console.log(`✓ gen-codex-skills: .agents/skills in sync (${dirs.length} categories, ${expected.size} files).`);
  process.exit(0);
}

for (const n of stale) unlinkSync(join(OUT_DIR, n));
for (const [name, content] of expected) {
  const output = join(OUT_DIR, name);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, content);
}
console.log(
  `gen-codex-skills: wrote ${expected.size} file(s)` +
    (stale.length ? `, removed ${stale.length} stale: ${stale.join(', ')}` : '')
);
