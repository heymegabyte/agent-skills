#!/usr/bin/env node
/**
 * gen-codex-skills.mjs — regenerate the `.agents/skills/` directory-format
 * mirror (OpenAI Codex / agentskills.io consumers) from the CURRENT numbered
 * category dirs. The mirror was a hand-cut Sep-2026 snapshot that drifted:
 * it still shipped retired categories (03, 17-20) and leaked Claude-adapter
 * paths (`~/.claude/**`, one machine-absolute `/Users/...`) into a non-Claude
 * surface (found by the fire-6 leak matrix; policy: rules/agent-neutrality.md).
 *
 * Behavior:
 *   - one portable `<name>/SKILL.md` directory per numbered category, full body copy (no
 *     lossy manual condensation) + a generated-file banner
 *   - one `<name>/agents/openai.yaml` with Codex UI metadata and a starter prompt
 *   - adapter-path mapping: `~/.claude/CLAUDE.md` → `AGENTSKILLS.md`,
 *     `~/.claude/` → `<agent-home>/` (legend in the banner), absolute
 *     `/Users/<name>/.claude/` collapsed the same way
 *   - stale outputs for retired categories are deleted
 *   - hard assertion: no `~/.claude` / `/Users/` survives in any output
 *
 * Usage:
 *   node bin/gen-codex-skills.mjs           # regenerate + report
 *   node bin/gen-codex-skills.mjs --check   # exit 1 if mirror drifted (CI)
 */
import { readdirSync, statSync, readFileSync, writeFileSync, unlinkSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, '.agents', 'skills');
const CHECK = process.argv.includes('--check');

const BANNER = `<!-- GENERATED by bin/gen-codex-skills.mjs from the category's SKILL.md — do not hand-edit.
     Path legend: \`<agent-home>\` = your AI tool's config directory
     (Claude Code: ~/.claude · Codex: ~/.codex · others: see your tool's docs). -->`;

function transform(body) {
  return body
    .replace(/\/Users\/[A-Za-z0-9_-]+\/\.claude\//g, '<agent-home>/')
    .replace(/\/Users\/[A-Za-z0-9_-]+\/\.local\/bin\//g, '')
    .replace(/~\/\.claude\/CLAUDE\.md/g, 'AGENTSKILLS.md')
    .replace(/~\/\.claude\.json/g, '<agent-home>.json')
    .replace(/~\/\.claude\//g, '<agent-home>/')
    .replace(/~\/\.claude\b/g, '<agent-home>');
}

// Portable consumers read name + description. Internal source metadata remains
// in the canonical numbered directories and must not leak incompatible types.
function slimFrontmatter(raw, dir) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return raw;
  const fm = m[1];
  const grab = (key) => {
    const r = fm.match(new RegExp(`^${key}: ?"?([^"\n]*)"?$`, 'm'));
    return r ? r[1].trim() : null;
  };
  const name = grab('name') || dir;
  const desc = grab('description') || '';
  const slim = [
    '---',
    `name: "${name}"`,
    `description: "${desc}"`,
    '---',
    '',
  ].join('\n');
  return slim + raw.slice(m[0].length);
}

function filesUnder(dir, prefix = '') {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    const absolute = join(dir, entry.name);
    return entry.isDirectory() ? filesUnder(absolute, relative) : [[relative, readFileSync(absolute)]];
  });
}

const NAMED_SKILLS = new Set(['terminal-development']);
const dirs = readdirSync(ROOT)
  .filter((n) => (/^\d\d-/.test(n) || NAMED_SKILLS.has(n)) && statSync(join(ROOT, n)).isDirectory())
  .sort();

const expected = new Map();
const titleCase = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join(' ');
const yamlString = (value) => JSON.stringify(value);
for (const dir of dirs) {
  const src = join(ROOT, dir, 'SKILL.md');
  if (!existsSync(src)) continue;
  const raw = readFileSync(src, 'utf8');
  const body = transform(slimFrontmatter(raw, dir));
  // Assert BEFORE the banner goes in — the banner's legend legitimately names ~/.claude.
  if (/~\/\.claude|\/Users\//.test(body)) {
    console.error(`✗ ${dir}: adapter-path leak survived transform — fix the mapping`);
    process.exit(1);
  }
  // Insert the banner right after the closing frontmatter fence.
  const out = body.replace(/^(---\n[\s\S]*?\n---\n)/, `$1\n${BANNER}\n`);
  const name = out.match(/^name:\s*"([^"]+)"$/m)?.[1];
  if (!name || !/^[a-z0-9-]{1,64}$/.test(name)) {
    console.error(`✗ ${dir}: portable skill name is missing or invalid`);
    process.exit(1);
  }
  expected.set(`${name}/SKILL.md`, out);
  const description = out.match(/^description:\s*"([^"]+)"$/m)?.[1] || `Use ${name} for its focused product workflow.`;
  const shortDescription = description.length <= 120 ? description : `${description.slice(0, 117).replace(/\s+\S*$/, '')}...`;
  const ui = [
    '# GENERATED by bin/gen-codex-skills.mjs — do not hand-edit.',
    'interface:',
    `  display_name: ${yamlString(titleCase(name))}`,
    `  short_description: ${yamlString(shortDescription)}`,
    `  default_prompt: ${yamlString(`Use $${name} to complete this task and verify the result.`)}`,
    '',
  ].join('\n');
  expected.set(`${name}/agents/openai.yaml`, ui);
  for (const [relative, content] of filesUnder(join(ROOT, dir, 'references'))) {
    expected.set(`${name}/references/${relative}`, content);
  }
}

const existingFlat = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).filter((n) => /^\d\d-.*\.md$/.test(n)) : [];
const generatedDirs = existsSync(OUT_DIR)
  ? readdirSync(OUT_DIR).filter((n) => {
      const skill = join(OUT_DIR, n, 'SKILL.md');
      return existsSync(skill) && readFileSync(skill, 'utf8').includes('GENERATED by bin/gen-codex-skills.mjs');
    })
  : [];
const staleDirs = generatedDirs.filter((n) => !expected.has(`${n}/SKILL.md`));
let drifted = [
  ...existingFlat.map((n) => `${n} (legacy flat layout)`),
  ...staleDirs.map((n) => `${n}/SKILL.md (stale)`),
];
for (const [relative, content] of expected) {
  const p = join(OUT_DIR, relative);
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (Buffer.isBuffer(content) ? !existsSync(p) || !readFileSync(p).equals(content) : cur !== content) drifted.push(relative);
}

if (CHECK) {
  // Also fail on mirror files git doesn't track — an unanchored .gitignore
  // 'skills/' once swallowed 8 of 23 (disk-synced, never shipped to consumers).
  const { execSync } = await import('node:child_process');
  const expectedSkillCount = [...expected.keys()].filter((path) => path.endsWith('/SKILL.md')).length;
  const tracked = execSync("git ls-files -- '.agents/skills/*/SKILL.md'", { cwd: ROOT })
    .toString().trim().split('\n').filter(Boolean).length;
  if (process.env.CI && tracked !== expectedSkillCount) {
    console.error(`✗ gen-codex-skills: ${expectedSkillCount} skill files on disk but only ${tracked} git-tracked — check .gitignore anchoring`);
    process.exit(1);
  }
  if (drifted.length) {
    console.error(`✗ gen-codex-skills: ${drifted.length} mirror file(s) drifted — run \`node bin/gen-codex-skills.mjs\`:`);
    for (const d of drifted) console.error(`  · ${d}`);
    process.exit(1);
  }
  console.log(`✓ gen-codex-skills: .agents/skills in sync (${expectedSkillCount} skills with Codex metadata).`);
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const n of existingFlat) unlinkSync(join(OUT_DIR, n));
for (const n of staleDirs) rmSync(join(OUT_DIR, n), { recursive: true, force: true });
for (const [relative, content] of expected) {
  const path = join(OUT_DIR, relative);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
console.log(
  `gen-codex-skills: wrote ${expected.size} file(s)` +
    (existingFlat.length || staleDirs.length
      ? `, removed ${existingFlat.length} legacy flat and ${staleDirs.length} stale directories`
      : '')
);
